# -*- coding: utf-8 -*-
"""抓取那道**准入闸**:这一笔「我参与了这一轮物化」留得下吗 —— 留不下就不许往下抓。

从 `kb.fetch_rounds` 里分出来的:那边是落盘协议(文件锁、缓冲、凭证、轮换)和对外
那几个动作,这边只定两件事 —— **什么算证据**,以及拒绝时那句话。单文件 700 行上限
见 CLAUDE.md;硬约束、事故形态和回归清单在 `docs/decisions/daily.md`。

拦的理由只有一条:**账本和那笔凭证能一起写不进去**,那一档继续抓就是产生一批
**永远不会进账**的文章 —— 重导时它们已经不算新文件,补不回来,而面板会笃定地报一个
少记的数。这一刀和「坏记录不许拦生产者」判的是两件事:别人那份记录读不出来是展示
问题(降级,照旧抓),自己这一笔欠账一处都记不下是记账能力没了(拦住,先修磁盘)。

**闸只认寿命和这笔欠账绑死的那两处证据**:账本里那条登记行(追加即不可撤,只随保留
窗口轮换)、那笔独立凭证(`kb.fetch_pending`,手里还欠行就在、行一落盘就撤)。被挡在
证据集外面的两样各是一次实测:

- 那笔**开工标记**:它的寿命是「那一轮运行」的,不是那笔欠账的 —— 两份终态一写上
  `pipeline_state._end_run` 就把它清掉,下一次起跑又原样覆盖(第 5 轮审查实测:两条
  旁路一起坏掉、采集器真写出第三篇、收尾正常跑完,全新进程仍报**确定的 2 条**)。
- **「此刻读不出账本」**:它只让我们看不见登记行。读一恢复,读侧就按剩下那几个完整
  子轮给出一个**确定的偏小值** —— 「这个请求读不到」推不出「将来的读者都会知道这一轮
  不全」,所以这一句退到那笔凭证上,两处都没留下才拦。

**而拒绝必须是干净的:准入结果是轮次生命周期的一部分。** 被明确拒绝的尝试既不许
增加「今天第几次」,也不许留下一个永远不交结束行的子轮把完整性永久压到下界,补写、
重放、重启都不能把它重新激活(审查实测的 F3:拒绝之后光读一次页面,那次压根
没起跑的尝试就变成了当天第一轮)。撤销那几行由 `fetch_rounds._drop` 做(缓冲是它
的),这里只回答「这算不算拒绝」。
"""
from __future__ import annotations

from pathlib import Path

from kb import fetch_pending


class NoEvidence(RuntimeError):
    """两处参与证据都留不下,所以这一轮没有往下抓(消息就是 `NO_EVIDENCE`)。

    **单独一个类型**,好让编排那一侧只把这一档的原因写进阶段卡片
    (`pipeline._run_pipeline` 的 crawl 分支)—— 拿 `RuntimeError` 当判据会把采集器
    自己抛的运行时错误也说成「抓取没有起跑」。
    """


# 两处证据都没留下时那一句拒绝的**唯一出处**。
NO_EVIDENCE = (
    '这一轮抓取的参与记录一处都没能留下（当日账本的登记行、独立凭证都没写上），'
    '所以没有往下抓：留不下记录的话这一轮新落的文章永远不会进账，面板会笃定地报'
    '一个少记的数，而重导时它们已经不算新文件、补不回来。先看一眼磁盘空间，以及'
    '数据目录和里面那个 fetch_rounds.* 的权限')


def rollback(unsaved: list[dict], objs: list[dict], key: str) -> list[dict]:
    """一次**被拒绝**的准入尝试撤掉之后,缓冲该剩下哪几行。

    **按对象身份(`id`)剔,不按值剔**:同批次别的子轮可能正欠着长得一模一样的行
    (两条 `partial` 标记就完全相同),按值剔会把别人的那一条也带走 —— 而那几行
    是别人的参与证据,这次拒绝一个字都不许动它们。

    挤出去换成的那条 `partial` 标记跟着撤,**但只在这个 key 再没有别的行时**:
    留着它就是另一条孤行(它那一轮的开轮行刚被我们撤掉),而同批次还有别的子轮
    欠着行时,那条标记记的是**它们**的不完整,不是这次尝试的。
    """
    mine = {id(o) for o in objs}
    kept = [o for o in unsaved if id(o) not in mine]
    rest = [o for o in kept if str(o.get('key') or '') == key]
    if (any('day' in o for o in objs) and rest
            and all(set(o) == {'key', 'partial'} for o in rest)):
        kept = [o for o in kept if o not in rest]
    return kept


def landed(rounds: list[dict], ok: bool, folder: Path,
           key: str, seg: str) -> bool:
    """这一笔欠账盘上还留得住吗 —— **追加没成功时才问这一句。**

    判的其实是**读侧会不会笃定地少报**:两处证据任一还在,`today()` 就会把这一轮
    压到下界或者答「不可确认」,那时继续抓是安全的。两处各是:

    · 账本里已经有这一轮这一个子轮:正路(同一个子轮重复开工时走这条)。
    · 本进程那几代凭证记着这一轮:「锁坏了、行攥在手里」那一档,**读回来确认**
      (`fetch_pending.put` 写不上是不出声的,它的返回值证明不了什么)。

    `rounds`/`ok` 要是**追加失败之后重读的那一份**:`write` 成了而 `fsync` 报错时
    那几行其实已经进了文件,拿追加之前那份快照问,会把一次已经留下痕迹的尝试当成
    拒绝(而拒绝要撤销,撤销之后盘上那条登记行就成了没人认领的一轮)。
    """
    # 读得出来才谈得上「登记行在盘上」;读不出来时它只是看不见,不能当证据用。
    if ok and any(r['key'] == key and seg in (r['segs'] | r['ends']) for r in rounds):
        return True
    return key in fetch_pending.mine(folder)
