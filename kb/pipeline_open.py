"""「有一轮开工了」单独落一笔盘 —— **收尾两份终态都写上了才清掉它**。

两份终态都是在 `_end_run()` 收尾时才写的。**都写失败那一档,磁盘上一个字都没有留下
这一轮的痕迹**:新身份、完成序号、终态和那笔留档诊断全在内存里,而重启把内存清空。
于是恢复看到的两份都是上一轮,`same_event` 正确地证明「这两份是同一次事件」—— 可它
证明不了「没有更新的一轮」:实测 B 轮(成功、范围是 B订阅)收尾时两份写入都注入
`ENOSPC`,重启后页头又显示 A 的 503、**空欠账、没有任何过期提示**,点「重试失败项」
导出阶段收到 `accounts: ['A订阅']`。进程在跑完之后、收尾之前被杀掉是同一档。

**现存的候选不等于「发生过的全部运行」。** 要能分出来,只能在**开工之前**就落一笔:
这一笔在、而磁盘上最新那一轮不是它,就说明有一轮跑过而结果没落下来。

判据故意只认「不是同一次事件」而不是「标记还在」:只有一份终态写失败那一档
(`scope`)标记也没清,可那一轮确实在历史里 —— 报失证就是误报。

**这一笔是起跑的前提,不是事后的提示。** 两头都钉住才闭合:写不上就不起跑
(`mark`),读不出来算「说不清」而不是「没有」(`gap`)。缺哪一头都会回到同一个
结局 —— 恢复把上一轮当成最新、重试去抓上一轮的范围,而页面上一切正常。
"""
from __future__ import annotations

from pathlib import Path

from kb.pipeline_persist import (
    _dump_bytes,
    _load_json_strict,
    _write_atomic,
    event_id,
)


# 边界落不下来时那一句拒绝的**唯一出处**(两个起跑入口都拿它,见
# `pipeline_state.mark_open`)。
NO_BOUNDARY = ('留不下这一轮的开工记录（{err}），所以没有起跑：数据目录写不进去的话'
               '这一轮的结果也会一起丢，而重启之后页面显示的就是上一轮、'
               '「重试失败项」会去抓上一轮的范围。先看一眼磁盘空间和数据目录的权限')


def mark(path: Path, run: dict) -> str:
    """落一笔开工标记。返回诊断(空串 = 写上了)。

    `run` 是**这一轮自己的**身份(`run_id` / `seq_gen` / `started_at` / `run_kind`),
    由起跑入口在发完新身份之后显式传进来。**不许拿常驻那份运行状态顶替** —— 这会儿
    它里面躺着的还是上一轮,而恢复过一次之后它的 `seq_gen` 是被恢复那一轮的出处(旧
    格式记录压根没有这个字段,于是是 None)。借来的出处让新一轮的标记认不出身份:
    实测旧格式恢复之后真起一轮 B、只让状态终态写失败,B 的标记没有可信身份而 B 的
    历史记录带着当前世代 —— 重启误报 `lost`,「一个字都没能留档」和那条打得开的
    B 历史自相矛盾。

    **写不上就不许起跑**(闸在两个起跑入口里,见 `pipeline_state.mark_open`)。
    原来是「写不上只记一笔诊断、照旧起跑」—— 那个取舍把代价算小了:它的代价不是
    「这一轮的结果将来可能说不清」,而是**系统会重新授权上一轮的范围、而用户看不见**。
    实测形态:A 轮翻译 503 正常留档;B 轮成功,开工标记和两份终态都注入 `ENOSPC`;
    B 照旧起线程、真跑完了导出,而重启之后页头显示 A 的 503、**空欠账、没有任何过期
    提示**,点「重试失败项」导出阶段收到 `accounts: ['A订阅']`。
    这一档**事后推不出来**:两份终态都是 A、逐字一致,而标记这一笔也没落上 —— 磁盘上
    没有一个字指向 B。
    「跑完之后、收尾之前再落一笔」也救不了它 —— 那时写盘同样是坏的。所以只剩一条:
    **边界落不下来就不要产生新的外部影响。**

    误报的代价很小而且看得见(这一轮不跑,面板上说清为什么;数据目录写不进去本来就
    是用户该知道的事,何况那一轮的终态也一样写不上);漏报的代价是静默按旧范围重抓
    一轮。顺序只能是这一头。

    **这一笔还同时是「有一轮抓取开过工」的证据**(`kb.fetch_claim` 读它):所以除了
    那一轮自己的身份,还要写下**这次抓取的业务身份**(`batch`,没有批次的独立运行
    留空,键按 `pipeline_batch.round_key_of` 还原)和**这一轮到底抓不抓**
    (`fetches`,判据是 crawl 在不在计划里 —— 在不在计划里就等于当日账本上开不开一
    轮)。两样都要:当日账本的每一次写都在一把会坏的文件锁后面,而这一笔是**起跑的
    前提**,它在就说明那一轮真的开过工。只记「标记还在」的话,一次只勾索引的运行就
    能让面板永久报「不完整」—— 身份必须按抓取/批次口径关联得上(第 4 轮审查明确
    钉的那一条)。老格式的标记没有这两个字段,读侧按「说不清」处理(见
    `fetch_claim.claim`),下一次起跑就覆盖掉了。
    """
    try:
        _write_atomic(path, _dump_bytes({
            "run_id": run.get("run_id", ""),
            "seq_gen": run.get("seq_gen"),
            "started_at": run.get("started_at", ""),
            "run_kind": run.get("run_kind", ""),
            "batch": str(run.get("batch") or ""),
            "fetches": 1 if "crawl" in (run.get("planned_stages") or []) else 0,
        }))
        return ''
    except Exception as exc:  # noqa: BLE001 - 任何落盘坏法都只是「这一笔没留下」
        return f'开工标记（{type(exc).__name__}）'


def clear(path: Path) -> None:
    """清掉开工标记。**只在两份终态都写上之后调** —— 清不掉就留着。

    留着的后果是下一次启动报一次失证(误报,顶多多跑一轮完整同步);反过来「没写上
    终态却把标记清了」是漏报,那一轮就此查不出来。
    """
    try:
        path.unlink(missing_ok=True)
    except OSError:
        pass


def gap(path: Path, known) -> str:
    """**开工标记指着的那一轮,在磁盘上留下过任何一份终态吗。**三档:

    · `''` —— **确证**没有未交付的运行:标记不在(上一轮正常收尾清掉了,或者这个库
      从没跑过),或者标记在、而候选里找得到同一次事件。
    · `'lost'` —— 那一轮跑过,磁盘上一个字都没留下。页面这一屏已经过期。
    · `'unknown'` —— **这一刻说不清**:标记读不出来(权限、I/O、半截写入、非 UTF-8
      字节),或者读出来的根不是字典(`null`、`[]`、一个字符串 —— 手改过、别的版本
      写的、坏块)。

    **「读不出来」和「不存在」必须分开,这是这个函数存在的全部意义。** 合成一个空值
    的话,一次瞬时读失败就被当成「确证没有未交付的运行」固化下来:实测只对第一次读
    开工标记注入 `PermissionError`(文件一个字节没动、另两份全可读),恢复就把上一轮
    当成最新、报空欠账,页面没有过期提示,真点一次重试导出阶段去抓了上一轮那个来源
    —— 而解除注入之后再读,同一份文件正确地报出 `lost`。能力一直在,被一次读失败
    吞掉了。所以这里和另两份落盘过**同一个**严格读取(`_load_json_strict`)。

    `known` 是两份落盘里读出来的全部候选(状态文件那一份 + 历史各轮)。判据是
    「它一份都没留下」,**不是「标记还在」、也不是「标记不是挑中的那一轮」**:
    只有一份终态写失败那一档标记也没清,可那一轮确实在历史里(`scope`);先后分不
    出来时挑中的是状态文件那一份,而另一轮明明在历史里 —— 那一屏不是过期,只是先后
    未知(`order` 自己会说)。两种写法都会多报一整类。
    """
    try:
        on_disk = _load_json_strict(path)
    except Exception:  # noqa: BLE001 - 任何读不出来都是「说不清」,不是「没有」
        return 'unknown'
    if on_disk is None:
        return ''
    if not isinstance(on_disk, dict):
        return 'unknown'
    got = event_id(on_disk)
    if not got:
        # 标记自己没有可信身份(写坏了、或者是别的版本写的):**宁可报失证** ——
        # 它存在就说明有一轮开工过,而我们证明不了它收尾了。
        return 'lost'
    found = any(got == event_id(one) for one in known if isinstance(one, dict))
    return '' if found else 'lost'
