def _target_closed(tail: str) -> bool:
    """这条 markdown 链接的目标在 `tail` 里就收尾了 —— 第一个**不平衡**的 `)`。

    判据取自 CommonMark 对 link destination 的定义:不带尖括号的目标里括号必须
    成对,第一个落单的 `)` 终止它。所以它回答的是「这条外层 URL 还开着吗」,
    不是"有没有括号"。

    **只对"紧前是 `](` 的起手式"问这一句**(见 `_nested` 第①步)。裸 URL 的路径里
    一个孤立的 `)` 是 sub-delims、完全合法(`https://example.org/a)b?u=<地址>`),
    拿这条去问它就会把一条**还开着**的外层 URL 误判成闭合 —— 容器找不到、候选被
    当成独立地址,别人那条地址被 `_drop` 永久摘掉。限定之后它当"开着",照旧判嵌套。
    """
    depth = 0
    for ch in tail:
        if ch == '(':
            depth += 1
        elif ch == ')':
            if not depth:
                return True
            depth -= 1
    return False


def _text_closed(head: str, tail: str) -> bool:
    """这个起手式落在一段 markdown 链接的**显示文字**里,而那段显示文字在候选之前
    就收尾了 —— 它压根不是一条 URL 的起点,是显示文字里的字。

    判据同样取自 CommonMark 对 `[text](dest)` 的定义,只是换成前一半:`]` 紧跟一个
    `(` 时它结束的是 link **text**。**而这要两头的证据,缺一头就不是显示文字:**
    - **左边**(`head`,起手式到 run 开头那一段)里有一个**还开着**的 `[` —— 那就是
      这段显示文字的开头;
    - **右边**(`tail`,起手式到候选那一段)里有一个**落单**的 `]` 紧跟着 `(` ——
      那是它的收尾,也就是紧接着的链接目标起手标记。

    **左边那一半是第 6 轮补的,而且它承重。** 第 5 轮只问了右边,理由写的是
    「"落单"(扫到它时 `[` 深度为 0)等价于它的 `[` 在这个起手式之前」—— **那句话
    是错的**:落单只说明"`tail` 里没有配对的 `[`",它既可能是「`[` 在起手式左边」
    (真·显示文字),也可能是「压根没有 `[`」 —— 而后者正是**一条外层 URL 自己
    内容里**的 `](`。于是
    `<https://example.org/share?text=read](https://x.com/Other/article/20002)>`
    这条完整的外部参考链接(尖括号 autolink,它的查询值里装着别人的文章地址)里,
    唯一那个外层起手式 `https://` 的 `head` 是**空的**、`tail` 是
    `example.org/share?text=read](` —— 落单的 `](` 成立,于是它被当成"显示文字"
    跳过,容器找不到、`nested=False`,别人那条地址被 `_drop` 摘成
    `…?text=read]( )`:`added=1`、`errors=[]`、`partial=[]`、全文照旧补上、
    水位照常推进、一行提示都没有,而 `DO NOTHING` 让这一篇**永久**停在残稿上
    —— 把 `]` 改成 `%5D` 再同步,真实 SQL 调用前的正文已经完整、`added` 仍是 0
    (2026-10-10 自由工作流第 6 轮审查实测;片段容器 `…/a](b)#<地址>`、真正的
    markdown 链接目标 `[share](https://example.org/a](b)?url=<地址>)`、旧式文章
    路径、t.co 短链,五种形态逐字相同,而上一轮版本 `90f949f` 对同一份输入全部
    逐字保留)。**而 `](` 出现在一条 URL 的查询值里是真实写法** —— 分享按钮把
    一段 markdown 塞进 `?text=` 就是它(同一条在真 `marked` 里渲染成**一条**
    指向 `example.org/share` 的链接,向本地回显端点发真实请求收到的查询值也逐字
    完整,见 `_nested` 第①步那段)。

    **这一道和 `_target_closed` 正好分开两族真实写法,差别只在"那个 `[` 在起手式的
    哪一边",而那正是这个深度计数回答的事:**
    - `[www.example.org](https://example.org/?q=foo)[article](<真地址>)` ——
      最左那个起手式 `www.` 是第一条链接的**显示文字**(用网址当链接文字是极常见
      的写法),它的 `]` 落单。不跳过它的话:它被当成一条"还开着"的外层 URL,
      而它的 tail 里有真目标的 `?q=foo` —— 于是 (b) 那条证据成立,这条推文
      **自己的**文章地址被判成"嵌在别人的查询值里",三条判据一条都不命中,那两条
      链接本身当成正文入库(`added=1`、`errors=[]`、`partial=[]`、接口调用 **0**
      次、水位照常推进、标题回落成「某某 的动态」),而 `DO NOTHING` 让它**永久**
      固定 —— 加空格再同步 `added=0`、库里和导出的 md 里仍然只有那两条链接
      (2026-10-10 自由工作流第 5 轮审查实测;显示文字换成 `https://example.org/`、
      目标换成片段、两种文章路径,四种形态逐字相同,而只把显示文字换成 `docs`
      就拿得到全文 —— 所以变量就是"显示文字像不像网址")。
    - `https://example.org/share?text=[read](<别人的地址>)` —— 那个 `](` 的 `[`
      在起手式**之后**、配对,所以不落单:外层 URL 还开着,候选确实嵌在它的查询值
      里,照旧判嵌套(第 4 轮那一族)。

    **`]` 后面必须紧跟 `(`**(口径同 `_target_closed` 那条"紧前必须是 `](`"):
    路径里的 `]` 是合法 URL 字符 —— IPv6 字面量
    (`https://[2001:db8::1]/docs#<地址>`)那个是配对的,`https://example.org/a]b?u=
    <地址>` 那个是落单的。不要求紧跟 `(` 就会把一条**还开着**的外层 URL 误判成
    "显示文字",别人那条地址照样被 `_drop` 永久摘掉。

    **第一个落单的 `]` 定胜负,不再往后找**:它不紧跟 `(` 时这条 URL 还开着
    (返回 False、照旧判嵌套),方向上偏向"保护别人的地址"。markdown 产物里显示
    文字一旦含 `]` 必然转义,所以这一档没有真实写法。

    **两头各有一条回归钉着**,而且它们的射程不重叠:去掉左边那一半,上面那五种
    参考链接的地址被永久剪断;去掉右边那一半(或者不数深度/不要求紧跟 `(`),
    第 4、5 轮那两族回来。
    """
    depth = 0
    for ch in head:
        if ch == '[':
            depth += 1
        elif ch == ']' and depth:
            depth -= 1
    if not depth:
        return False
    depth = 0
    for i, ch in enumerate(tail):
        if ch == '[':
            depth += 1
        elif ch == ']':
            if depth:
                depth -= 1
            else:
                return tail[i + 1:i + 2] == '('
    return False


def _nested(m: re.Match) -> bool:
    """这个匹配是嵌在**别人**那条 URL 里,不是这条推文自己写的地址。

    **它是起点那一头唯一的判据**,两档候选一视同仁地过(见模块顶上分档那段)。
    判据三步,`_SEPARATORS` 那段注释记着"按紧贴的那一个字符判"两次栽在哪儿:

    ①**紧贴左边那一段连续 URL 字符里没有另一条 URL 的起点 → 不是嵌套。** 那一段
      就是作者自己写的一截文字,紧贴的那些字符是他的标点。`全文=<地址>`、
      `阅读地址/<地址>`、`读过这篇吗?<地址>`、`新文章...<地址>` 全在这一档放行。
      两处细节各有理由:
      - **只往左吃 URL 合法字符,不是"数到最近的空白"**。外层 URL 的结构字符必须
        紧邻它自己那条 URL 的 authority/path,而正文里的汉字天然落在字符集外面
        —— 数到空白的话 `https://example.org/doc,<地址>`(两条地址用逗号紧连)
        这种**真**地址会被误拒,而误拒 = 漏认 = 空正文永久固定。**"URL 合法字符"
        按 RFC 3986 取全集**,见 `_URL_RUN` 那段:少认一个,外层起点就丢了、别人
        那条地址被从中间剪断。
      - **起手式只认 `https?://` 和 `www.`**(口径同 `daily_refs._autolinked`,
        大小写不敏感)。于是「裸域名 + 结构字符 + 嵌一条完整 X 地址」
        (`example.org?<地址>`)这道缝留着 —— 那不是任何真实写法。
      - **`](` 是一条 markdown 链接目标的「起手标记」,不是「扫描终止符」。**
        RFC 3986 把 `(` `)` `[` `]` 都算合法 URL 字符,而 feedgrab 的产物正文是
        **markdown** —— 相邻的几条链接之间一个空白都没有,整段连成一个 run。于是
        `[share](https://example.org/?q=foo)[docs](https://docs.example.org/)[article](<真地址>)`
        里这条推文**自己的**地址被判成"嵌在第一条参考链接的查询值里",三条判据一条
        都不命中:那几条链接本身当成正文入库,`added=1`、`errors=[]`、`partial=[]`、
        接口调用 **0** 次、水位照常推进、标题回落成「某某 的动态」,而 `DO NOTHING`
        让它**永久**固定(2026-10-10 自由工作流第 3 轮审查实测,两种文章路径逐字
        相同)。
        **第 3 轮把它当终止符,那个前提被第 4 轮审查用三项实证推翻了** ——
        依据原来是"`]` 在一条合法 URL 里只用于 IPv6 字面量收尾,后面紧跟一个 `(`
        不可能出现";而同一条
        `<https://example.org/share?text=[read](<别人的地址>)>` 在页面加载的真
        `marked` 里渲染成**一条**指向 `example.org/share` 的链接、Chromium 的
        `new URL()` 原样保留它且 `searchParams.get('text')` 返回完整的
        `[read](<别人的地址>)`、向本地回显端点发真实 HTTP 请求收到的原始查询也逐字
        完整。**分享按钮把一段 markdown 塞进查询值是真实写法**,那个 `](` 是**外层
        URL 的内容**。停在那里的后果是 run 丢掉外层起点和 `?`、容器找不到,别人那条
        地址被摘成 `…?text=[read]( )`,`_first` 还为它白发一次长文询问,而
        `DO NOTHING` 让这一篇永久停在残稿上(把方括号改成 `%5B`/`%5D` 再同步,真实
        SQL 调用前的正文已经完整、`added` 仍是 0;片段里同形、t.co、两种文章路径
        逐字相同)。
        **所以 `](` 只用来分类起手式,不用来截断扫描**:往左一路扫到底,再逐个起手式
        问一句「它到候选这儿还开着吗」,**`[text](dest)` 的两半各有一条收尾判据,
        谁成立都跳过这个起手式**:
          - 它是一条链接的**目标**(紧前是 `](`)→ `_target_closed`,第一个落单的
            `)` 收尾它;
          - 它落在一段链接的**显示文字**里 → `_text_closed`,**左边**有一个还开着
            的 `[`(那段显示文字的开头)、**右边**有一个落单的 `](`(它的收尾)。
        **第二道是第 5 轮补的,而且它不是第一道的冗余**:`[www.example.org](https://
        example.org/?q=foo)[article](<真地址>)` 里最左那个起手式 `www.` 紧前是 `[`
        —— 第一道压根不问它,于是它被当成一条"还开着"的外层 URL,而它的 tail 里有
        真目标的 `?q=foo`,这条推文**自己的**地址又一次被判成"嵌在别人的查询值里",
        那两条链接当成正文入库、接口调用 **0** 次、`DO NOTHING` 永久固定(2026-10-10
        自由工作流第 5 轮审查实测;**只把显示文字换成 `docs` 就拿得到全文** ——
        变量就是"显示文字像不像网址",而用网址当链接文字是极常见的写法)。
        两道的分界线是**那个 `[` 在起手式的哪一边**:落单 ⇒ 它在左边、起手式在显示
        文字里;配对 ⇒ 它在右边、起手式所在的那条外层 URL 还开着(上面那条分享
        查询值就是)。
        **而"落单"只是必要条件,左边真的有那个 `[` 才是充分条件 —— 第 5 轮漏了这
        一半,第 6 轮补上**:`head` 为空(也就是整个 run 就是一条外层 URL)时落单
        照样成立,于是
        `<https://example.org/share?text=read](https://x.com/Other/article/20002)>`
        这条完整的外部参考链接被当成"显示文字"跳过,别人那条地址被摘成
        `…?text=read]( )` 并由 `DO NOTHING` 永久固定(2026-10-10 自由工作流第 6 轮
        审查实测,五种形态见 `_text_closed` 的 docstring)。两头各有自己的回归,
        射程不重叠。
        五件事各有一条回归钉着:**两条紧跟限定都不能省**(裸 URL 路径里孤立的 `)`
        和 `]` 都是合法字符,不限定会把还开着的外层误判成闭合)、**只认不平衡的 `)`**
        (链接目标里的平衡括号是它路径的内容,`[a](https://example.org/docs(v2)#<地址>)`
        照旧是容器)、**显示文字那一道要左右两头都有证据**、**闭合了要继续往后找下
        一个起手式**
        (`[a](…?q=1)https://evil.example/?u=<地址>` 的容器是后面那条)。
        **没有引入 markdown 解析**:三条判据都取自 CommonMark 对 `[text](dest)` 的
        定义(目标起手是 `](`、不带尖括号的目标由第一个落单的 `)` 终止、`]` 紧跟
        `(` 时收尾的是 link text),而要判的是
        "这一个起点是不是一条 URL 的起点" —— **切分**问题、不是解析问题(口径同
        第 4、5、6 轮答复的 `urlsplit` 路线)。
        **边界之后那一段仍然是同一条 URL** —— 它恰好是**同一条链接的目标**,照旧
        逐字过下面那两种证据:`[a](https://example.org/?u=<别人的文章地址>)` 里那条
        照旧判成嵌套、一个字不动。
        **换成闭合判据之后第 3 轮记的那道缝顺手好了**:一条链接闭合之后**紧贴**一个
        裸 URL(`[share](https://example.org/?q=foo)https://x.com/…`)原来会被判成
        嵌套(那里没有 `](` 可认),现在那条闭合的目标被正确跳过。
      **多个起手式时取最左那一个**(`search` 而不是 `finditer` 的末项)。它回答的是
      「候选落在**哪一条**外层 URL 里」,而那永远是最外面那条:一条 URL 的查询串
      和片段**只被空白和 `<` 终止**,所以最左那个起手式一旦进了 `?` / `#`,从那里
      到候选之间的每一个字符(包括中间**又一条**完整 URL)都还在它的值里面。
      **取最后一个是上一轮自己开出来的破洞**(2026-10-10 自由工作流第 2 轮审查
      实测):分享按钮生成的 `?text=` 常常装着两条网址
      (`…/share?text=Read+https://docs.example.org/+<地址>`),取末项时 `head` 落在
      内层那条 `https://` 后面,只看得见 `docs.example.org/+` —— 没有 `?#`、紧前
      又是 `+`,于是判成"不是嵌套",别人那条参考地址被从中间永久剪断(库里和导出
      的 md 都只剩 `…+`,而 `added=1`、`errors=[]`、`partial=[]`、水位照常推进;
      内层换成 `www.`、分隔符换成 `%20`、片段里两条、内层是 t.co 短链,五种形态
      逐字同样)。当时写的理由是"候选只可能嵌在紧挨着它左边那条 URL 里" ——
      **那句话对路径段成立、对不透明值容器不成立**,而后者正是 (b) 那条证据管的
      那一档。
    ②**有外层起点时,再看候选占的是不是外层 URL 的一个结构位置**,两种证据任一
      成立即算嵌套:
      - (a) 紧前那**一个**字符是 `_SEPARATORS` 之一 —— 它占着一个路径段 / 查询值
        / 片段的位置(`?u=<地址>`、`#<地址>`、`&u=<地址>`、`/go/<地址>`);
      - (b) **最左那个「还开着」的**外层起手式之后出现过 `?` 或 `#` —— 候选落在**查询串或
        片段**里,而那是不透明的值容器,里面写着一条完整 URL 几乎必然是转发/重
        定向/分享参数(`?text=Read+<地址>`、`?text=Read%20<地址>`、
        `?target=(<地址>)`)。**值里装着不止一条网址时也是同一个答案** ——
        `?text=Read+https://docs.example.org/+<地址>` 的查询值逐字就是
        `Read https://docs.example.org/ <地址>`(`+` 是编码过的空格,不是"外层
        URL 到此为止、另起一条"的标记),两条都是分享文字的内容。
      **两条缺一不可**(2026-10-10 自由工作流第 1 轮审查实测):只有 (a) 时上面那
      三种分享查询值一条都认不出来,别人那条参考地址被从中间永久剪断(库里和导出
      的 md 都只剩 `…?text=Read+`,而 `added=1`、`errors=[]`、`partial=[]`、水位
      照常推进);只有 (b) 时 `…/go/<地址>` 这种**路径段**嵌套漏掉。
    ③**都不成立 → 放行。** 落在这一档的只有"外层 URL 的**路径**里用内容字符
      (`,` `+` `(` `;` …)紧连着写了第二条地址",人读的时候那就是两条并列的地址
      —— `https://example.org/doc,<地址>` 正是它,回归里反过来钉着。

    **已知留着的一道缝**(和上面那条放行样本同形,方向相反):进了外层的**查询串**
    之后再用内容字符紧连一条并列地址(`https://a.org/?x=1,<地址>`)会被 (b) 判成
    嵌套,**中间还夹着另一条完整 URL 时同样**
    (`https://a.org/?k=1,www.b.org/doc,<地址>`)—— 后者就是上面那个破洞原来救的
    那种写法,改成取最左之后一并落进这道缝里。两件事让这个取舍成立:①按 URL 语法
    它**本来**就是 `a.org` 的查询值(`,` 是 sub-delims、合法),判成嵌套是语法
    正确的那一边;②它不是真实写法 —— 人把几条地址并列写出来**必然带空白**,而
    空白是 ①那步往左扫描的天然边界(`https://a.org/?k=1 <地址>` 的 run 是空的,
    一步就放行)。反过来"分享按钮把两条网址塞进同一个查询值"没有空白可依,
    它只能靠这条判据。
    两头都是永久损坏,线划在"查询串/片段是不透明值容器、路径是层级结构"上
    —— 这一条可解释,而"紧贴的那个字符是不是标点"不可解释(上面两次就是它栽的)。

    **markdown 那一头也留着一道同形的缝**:一条链接闭合之后**紧贴**一个裸 URL
    (`[share](https://example.org/?q=foo)https://x.com/…`、
    `[share](https://example.org/?q=foo)(https://x.com/…)`)照旧会被判成嵌套
    —— 那里没有 `](` 可认,而 `)` 一律当终止符会把上面那条外层路径括号的样本
    重新破掉。它不是任何真实写法:markdown 产物里链接的目标总写在 `](…)` 里,
    而人手写两条并列地址必然带空白。

    **往左的扫描是从右往左逐字走的,不是在左半边做一次 `re.search`。** 两种写法
    取的是同一段(末尾那段连续的 URL 字符),但后者让正则引擎从左半边的**每一个
    位置**各试一次 `[…]*$`,于是正文越长越慢:实测一条「长英文正文 + 空格 + 句末
    问号 + 文章地址」的推文,`needs_article` 在 1000 字符上 0.002 秒、10000 字符
    0.202 秒、25000 字符 1.256 秒(2026-10-10 第 6 轮审查测时)。从右往左只扫
    实际那一段(通常几十个字符),上面那条样本是常数时间 —— 而推文正文对
    premium 用户能写到两万字以上。
    """
    text, start = m.string, m.start()
    if not start:
        return False
    i = start
    while i and text[i - 1] in _URL_RUN:
        i -= 1
    run = text[i:start]
    for outer in _OUTER_START.finditer(run):
        head, tail = run[:outer.start()], run[outer.end():]
        if head.endswith('](') and _target_closed(tail):
            continue
        if _text_closed(head, tail):
            continue
        return text[start - 1] in _SEPARATORS or any(c in '?#' for c in tail)
    return False


def _first(pat: re.Pattern, text: str) -> re.Match | None:
    """第一个**不是**嵌在别人 URL 里的匹配。`needs_article` 判据① 的入口。"""
    return next((m for m in pat.finditer(text) if not _nested(m)), None)


def _drop(pat: re.Pattern, text: str) -> str:
    """只摘掉**不是**嵌在别人 URL 里的那些匹配,别人的地址一个字不动。

    和 `_first` 共用 `_nested`:两个消费方的方向相反(`search` 宁可认宽、`sub`
    宁可少删),但"这个起点算不算一条新 URL 的起点"只能有一份口径。
    """
    return pat.sub(lambda m: ' ' if not _nested(m) else m.group(0), text)


def lead_text(body: str) -> str:
    """把正文里「这条推文自己说的话」摘出来:去掉转推上下文那行和光秃秃的链接。

    三样东西都不算"说了话":`_entry` 给转推加的那行 `> 上下文`、指向长文的裸链接、
    以及 t.co 短链。剩下的才是作者写在推文里的字 —— 它决定这一条要不要去补正文,
    补到之后也作为开头留在正文里。

    **「指向长文的裸链接」认的是 `_ARTICLE_LINK` 那两种形式,和 `needs_article`
    判据① 同一份口径**(就是同一条正则 —— 两处各写一份必然漂)。两处都要对是因为
    它们各管一头:判据① 决定"这一条要不要去问",这里决定"问到之后正文开头留什么"。
    少认一种形式时,即使别的判据救回了这一条(浏览器通道的卡片信号),那条地址也会
    原样留在库里那篇正文的开头 —— 它不是作者写的字,是 X 替他渲染成卡片的那条链接
    (2026-10-09 实测:规范形式下库里那篇正文是「我写了一篇新文章」、紧跟着那条
    `https://x.com/…/article/9`、然后才是全文)。

    **摘掉的只能是那条地址本身,紧挨着它的标点和文字一个都不许动**(尾巴的口径在
    `_URL_TAIL`)。两条正则的尾巴原来都是"吃到下一个空白为止"(`\S*` / Unicode 的
    `\w+`),而中文不带空格:`…/article/10001，重点看第三节。` 整句都被当成地址
    删掉,`added=1`、`errors=[]`、水位照常推进,而 `DO NOTHING` 让这一篇**永久**
    只剩前半句 —— 重复同步也补不回来(2026-10-09 实测,中文括号/方括号、
    `?s=20` 或 `#sec3` 之后紧跟中文、以及英文的 `. ` `) ` 收尾逐字同样;两种路径
    形式和 t.co 那条都有这个病)。

    **左边同理:起点必须是一条 URL 的起点**(`_URL_HOST` + `_nested`)。两条正则里
    的 `x.com` / `twitter.com` / `t.co` 只是一段字符,不加这道闸时
    `https://fxtwitter.com/Example/article/10001` 这类**合法的外部地址**会从中间
    被当成起点、后半截删掉,末态和上面逐字相同(2026-10-09 实测:库里和导出的 md
    里那条参考地址只剩 `https://fx`,而 `added=1`、`errors=[]`、`partial=[]`、
    水位照常推进)。整条嵌在别人查询串/片段里的那种(`https://example.org/#<地址>`)
    同理一个字不动,而**句末问号紧贴的那一条是作者自己的地址,照摘** —— 这两件事
    靠的是 `_nested` 看一眼那个 `?`/`#` 左边是不是一条 URL,不是看它是哪个字符。
    """
    lines = [ln for ln in (body or '').splitlines() if not ln.lstrip().startswith('>')]
    return _drop(_TCO, _drop(_ARTICLE_LINK, '\n'.join(lines))).strip()


def quote_lines(body: str) -> str:
    """把正文里的转推/引用上下文摘出来 —— 就是 `lead_text` 滤掉的那几行 `> …`。

    **`lead_text` 滤掉它们是对的,但补完文章正文不能跟着把它们一起丢掉。**
    那一行是「谁转发了这篇文章」的唯一记录:`x_browser._entry` 把它放在正文开头
    (`> {context}`),因为 `feed_items` 里没有别的地方放这个标记,而它决定了这
    一条是不是本人的观点。原来 `fill` 拿 `lead_text` 的结果当重建正文的唯一依据,
    于是**正文补上了、谁转发的没了** —— 数据库、导出的 md 和阅读页三处一起缺
    (2026-10-09 审查实测,阴性对照是不开长文补全时上下文照旧留着),而
    `put_items` 是 `DO NOTHING`,缺了就再也补不回来。

    所以这两半各摘各的,再和文章正文按原顺序合并:上下文 → 介绍 → 正文。
    """
    keep = [ln for ln in (body or '').splitlines() if ln.lstrip().startswith('>')]
    return '\n'.join(keep).strip()


def article_page(url: str) -> str:
    """推文 URL → 文章页 URL。认不出来返回空串。"""
    m = _ARTICLE_PATH.match((url or '').strip())
    return f'{m.group(1)}/article/{m.group(2)}' if m else ''


# 时间线采集给这条推文挂的「它带着一张长文卡片」信号(`x_browser._COLLECT_JS`
# 从 DOM 里读那张卡片的链接)。**它只是信号,地址不用它** —— 文章页地址由推文
# 自己的 URL 推出来(见 `article_page`),"有没有长文"的结论由接口/页面那一侧给。
# 所以信号误判的代价只是一次白跑的询问(答复正好是"它没有长文"、照旧入库),
# 绝不会把别人的文章记到这条推文头上。
HINT = 'article_hint'


def _strip_hint(entry: dict) -> dict:
    """摘掉那个内部信号键 —— 它不进 `feed_items`:`put_items` 把**整份条目**
    哈希成 `content_hash`,多一个只有采集期间才有意义的键会让同一条推文在两条
    通道上算出不同的哈希。"""
    return {k: v for k, v in entry.items() if k != HINT} if HINT in entry else entry


def needs_article(entry: dict, *, links_only: bool = False) -> bool:
    """这一条要不要去问一次长文。三条,各管一种形态:

    ①**正文里明写着一条文章地址** —— 这是确定的信号,feedgrab 的产物正文就是它
      (推文的 t.co 被展开成了文章地址),哪怕作者还写了别的话。`/i/article/<id>`
      和 `/<handle>/article/<id>` **两种形式都算**,见 `_ARTICLE_LINK`:展开成哪
      一种由上游和 X 说了算,只认一种时另一种会把那条链接本身当正文入库、而且
      `DO NOTHING` 之下永久改不回来。**紧贴在它前面的标点一个都不许挡住它**
      (省略号、波浪号、英文冒号、句末问号…… 口径在 `_URL_HOST` 和 `_nested`):
      挡住的末态和少认一种形式逐字相同。整条嵌在别人 URL 里的那种不算 —— 那是
      别人的文章,见 `_nested`。
    ②**时间线上看见了那张长文卡片**(`HINT`)—— 浏览器通道那边 X 把链接藏起来
      改渲染成卡片,所以「写了一句介绍 + 一张卡片」的推文正文**非空**,①②之外
      没有任何信号;而卡片本身在 DOM 里是一条 `/i/article/<id>` 或
      `/<handle>/article/<id>` 链接,读出来当信号正好。
    ③**推文自己一个字都没说** —— 同样是卡片那条路,只是作者没写介绍,于是我们
      手里只剩一条空正文。纯图、纯视频推文也满足它,那是故意的:没有别的办法
      分辨,而问一次的答复正好把它们分开(返回 None = 它没有长文)。

    **不拿「正文里有 t.co 短链」当信号**:那可能是图片、引用推、任意外链,按它
    发请求等于给一大半推文各买一次调用,而换回来的多半是"它没有长文"。

    `links_only` 是桥接通道那一档:它拿到的是桥接实例给的推文文本,长文在那儿
    的形态**只有** ① 一种(正文就是展开后的文章地址),而 ③ 在那条路上多半是纯
    图推文 —— 一轮几十条各买一次询问换不回东西,所以只认 ①。
    """
    if not entry.get('url'):
        return False
    body = entry.get('body') or ''
    if _first(_ARTICLE_LINK, body):
        return True
    if links_only:
        return False
    return bool(entry.get(HINT)) or not lead_text(body)
