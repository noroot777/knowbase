# -*- coding: utf-8 -*-
"""X 文章地址的识别,和把它从推文正文里摘掉。

**从 `x_article.py` 搬出来的一整块**(它越过了 700 行上限):那边是「取一次长文
正文」(接口、浏览器后路、Draft.js 渲染),这边只回答两个问题 ——
①**这一条要不要去问一次长文**(`needs_article`);②**问到之后,正文开头留什么**
(`lead_text`,连同它的对偶 `quote_lines` —— 它收回 `lead_text` 滤掉的那几行
转推上下文,两半各摘各的才拼得出完整正文)。两个问题共用同一份地址识别(两条
正则 + 起点闸 + 尾巴),所以它们必须待在一起:各写一份必然漂,而漂出来的后果是
空正文或者作者的字永久消失(`put_items` 是 `ON CONFLICT(key) DO NOTHING`,
一条推文入库之后就改不回来了)。

**两个消费方的方向正好相反**,这是读这个模块时唯一要先记住的事:
`needs_article` 是 `search`(漏认 = 空正文永久固定,所以宁可认宽),`lead_text`
是 `sub`(多删 = 作者写的字永久消失,所以宁可少删)。下面每一条规则的取舍都是
按这两个方向算出来的。

`x_article` 原样再导出这里的名字(`HINT` / `lead_text` / `needs_article` /
`article_page` / `_first` / `_ARTICLE_LINK` / `_URL_RUN` …),所以对外和对测试
的口径一个字都没变 —— 口径同 `taxonomy.py` 拆出 `taxo_tables.py` 那次。
"""

from __future__ import annotations

import re

# 一条 URL 写在推文正文里时,它从哪儿**起**算。下面两条正则都用它,而它们都是拿去
# `sub` 掉的 —— 两条正则里的 `x.com` / `twitter.com` / `t.co` 都只是一段字符,
# **压根不要求它是主机名**,于是别人家的地址里出现这一段就被当成起点,后半截被
# 删掉,而 `put_items` 的 `DO NOTHING` 让这种删除**永久固定**。
#
# 实测被改坏的形态(2026-10-09,每一种都是合法的外部地址):
#   `https://fxtwitter.com/Example/article/10001` → `https://fx`(镜像站,`fx` 后面
#     那一段逐字就是 `twitter.com/<handle>/article/<id>`)
#   `https://notx.com/Example/article/10001`      → `https://not`
#   `https://help.x.com/Example/article/10001`    → `https://help.`(子域名)
#   `https://my-x.com/Example/article/10001`      → `https://my-`
#   `https://example.org/docs/x.com/Example/article/10001` → `https://example.org/docs/`
#     (真实主机名是 `example.org`,`x.com` 只是它路径里的内容)
#   `https://evil.example/?u=http://t.co/aBcD12&next=1` → 查询参数被删掉一截
# 这几条同时还让 `needs_article` 判据① 误判成"要去问一次长文",白跑一次询问。
#
# **判据按候选自己带不带 scheme 分成两档,因为这两档要排掉的东西根本不是一回事。**
# 合成一档(一律禁"URL 内部字符紧贴")的后果实测过:**省略号或波浪号紧贴的真地址
# 被拒**,`needs_article` 三条判据一条都不命中,于是那条链接本身当成正文入库 ——
# `added=1`、`errors=[]`、`partial=[]`、水位照常推进、标题回落成「某某 的动态」,
# 而 `DO NOTHING` 之下重复同步也补不回来(2026-10-09 实测
# `我写了一篇新文章...https://x.com/Example/article/10001` 与 `新文章~…`,两种路径
# 形式各一次,浏览器通道没读到卡片信号时逐字同样)。`.` 和 `~` 在这里有两个互相
# 冲突的身份:在 `help.x.com` / `my-x.com` 里它们是**域名的一部分**,在
# `新文章...<地址>` 里它们是**作者的标点** —— 单看紧贴的那一个字符分不开,而分档
# 之后压根不用分:
#
# ①**自带 scheme 的候选**(起点那一头在正则里**一个字符都不限**,全交给
#   `_nested` 按上下文判)。`https://` 本身就宣告"一条新 URL 从这里开始",所以
#   域名后缀那一类从定义上就不可能 —— 要排的只有"它嵌在另一条 URL 里",而那是个
#   **上下文**问题,不是"紧贴的那一个字符是什么"问题:判据连同它两次栽的实测写在
#   `_SEPARATORS` 和 `_nested` 那两段注释里。
# ②**裸域名的候选**(`_BARE_HEAD`,`x.com/<handle>/article/<id>` 不带 scheme)。
#   这一档的起点就是主机名的第一个字符,所以域名后缀和路径嵌套都要排,禁止集是
#   「URL 内部字符」那一整套(`_URL_CHARS`)—— 它和分档之前那道闸**逐字相同**,
#   分档只是给①松了绑。代价是"标点 + 裸域名"一律被拒 —— `...x.com/…`、
#   `读过这篇吗?x.com/…`、`第三节#x.com/…` 都在里面。取舍是故意的,裸写法不是 X
#   展开出来的形态(t.co 展开必带 scheme,feedgrab 的产物也是完整 URL),而域名后缀
#   误认会把**别人的文章**记成这条推文的内容,这个方向上宁可多排(口径同 `HINT`
#   那条"排掉引用推容器里的卡片")。要给这一档也开口子得在这里再拆一份字符集
#   (`_URL_RUN` 那一份管的是另一件事,见它自己那段注释),多一份要对齐的口径换一种
#   没有真实触发路径的写法,不值。
#   **`_nested` 对两档一视同仁地跑**(判据只有一份),只是这一档的正则已经把全部
#   URL 内部字符挡在外面了,能走到 `_nested` 的候选紧前字符必然落在
#   `_URL_RUN - _URL_CHARS`(`!$'(),;:[]*`)或者字符集外面 —— 所以它在这一档上
#   只可能**多拒**,不可能少拒。不给它开特例,是因为"这个起点算不算一条新 URL 的
#   起点"不该有两份答案。
#
# **禁止集必须逐个列出 ASCII,不许写 `\w`**:Python 的 str 模式下它是 Unicode 的
# (`re.match(r'\w+', '中文')` 当场命中),于是「我写了一篇新文章:<地址>」里那条
# **真**地址会被自己的前一个汉字挡住 —— 那是漏认,而漏认 = 空正文永久固定,
# 比多删一处还重一个量级(口径同 `_URL_TAIL` ① 那条坑,`_TCO` 原来就是这么漏的)。
# **`:` 两档都放行**:`参考:https://x.com/…/article/1` 这种英文冒号紧贴的写法里
# 那条地址是真的,禁掉它就摘不下来了。
# **没有改成「先切出 URL 再 `urlsplit` 校验主机名」**:正文是自由文本,"从哪儿到
# 哪儿是一条 URL"本来就是这条正则在回答的问题,再加一层解析只是把同一个边界问题
# 挪到切分那一步,还多一份要对齐的口径;`_nested` 直接回答"这个起点是不是一条新
# URL 的起点",判据和匹配待在同一条规则里。
_URL_CHARS = r'A-Za-z0-9._~%+/=&?#@\-'
_BARE_HEAD = r'(?<![' + _URL_CHARS + r'])'
_URL_HOST = r'(?:https?://|' + _BARE_HEAD + r')'
# 外层 URL 的**结构分隔符**:候选紧贴在它们右边时,占的正是一个路径段 / 查询值 /
# 片段的位置。它只是 `_nested` 第二步的**一半**证据,不是一道独立的闸 —— 单看紧贴
# 的那一个字符回答不了"这是嵌套还是作者的标点",这五个字符在正文里全都另有身份。
#
# **「按紧贴的那一个字符判」栽过两次,两次都是同一个方向 —— 把一条**真**地址挡在
# 正则层面,而漏认 = 空正文永久固定:**
# ①**定宽后视一律拒 `=` `&` `/`(2026-10-10 自由工作流第 1 轮审查实测)。**
#   `全文=<文章地址>`、`阅读地址/<文章地址>`、`Read &<文章地址>` 里那条**真**地址
#   被自己前面那个标点挡在正则层面 —— `_nested` 压根没有机会发问,`needs_article`
#   三条判据一条都不命中,于是那条链接本身当成正文入库:`added=1`、`errors=[]`、
#   `partial=[]`、接口调用 **0** 次、水位照常推进、标题回落成「某某 的动态」,而
#   `DO NOTHING` 之下重复同步也补不回来(两种路径形式各实测一次;同一句话改成
#   `全文= <地址>`、加一个空格就正常)。`=` 在 `v1?x=1` 这类正文里是赋值号、`/`
#   在「阅读地址/订阅」里是并列号、`&` 在「A &B」里是连词 —— 都不是结构字符。
# ②**一律拒 `?` 和 `#`(2026-10-09 第 4 轮审查实测)。**
#   `Have you read this?<文章地址>`、`读过这篇吗?<文章地址>`(中文不带空格,半角
#   问号紧贴是常见写法)、`What#<文章地址>` 里那条真地址同样被挡住,末态逐字相同。
# **而反过来一律放行也不行**:`https://example.org/#<文章地址>`、
# `https://evil.example/?u=<文章地址>`、`…/go/<文章地址>` 这些整条嵌在别人 URL 里
# 的写法照旧要一个字不动(口径同上面那六种外部地址)。
#
# 所以这五个字符一个都不写进正则,**起点算不算一条新 URL 的起点由 `_nested` 按
# 上下文回答**,判据三步见它自己那段 docstring。
_SEPARATORS = '=&/?#'
# 「一条**已经开始**的 URL 内部能出现的 ASCII 字符」,按 RFC 3986 的字符表取
# **全集**,一个不少:unreserved `A-Za-z0-9-._~`、pct-encoded 的 `%`、
# sub-delims `!$&'()*+,;=`、gen-delims `:/?#[]@`。下面那四段字面量就是照这四类
# 分开写的,**改它之前先读完这一整段**。
# **和 `_URL_CHARS` 不是一份,也不许合并**:那一份是②档的禁止集(加宽它等于把
# 「英文逗号/括号 + 裸域名」也拒掉,扩大②档已记的取舍),这一份是 `_nested` 往左追
# 外层起点时能跨过的字符。两者回答的根本不是同一个问题,而这一份**少认一个字符,
# 外层起点就追不回来**:`_nested` 误答"不是嵌套",于是别人家查询串/片段里那条 X
# 文章地址被当成这条推文自己的,`_drop` 把它删掉,而 `DO NOTHING` 让这种删除
# **永久固定**。同一道缺口还让判据① 把这些推文一律误判成"要去问一次长文"。
#
# **"见一个样本补一个"栽过两次,所以这里取标准全集、并由回归钉住它就是全集**
# (`test_x_article_urlrun.UrlRunContractTests`:和 RFC 3986 的字符表逐字相等,
# 而且不含空白与非 ASCII)。两次各自的实测:
# ①第 5 轮 —— 原来复用 `_URL_CHARS` 再补一个 `:`,于是 sub-delims 里 `(` `)` `;`
#   `$` `'` `,` `!` `*` 八个合法**路径**字符一个不认:
#   `…/docs(v2)#https://x.com/Other/article/20002` 在库里和导出的 md 里都只剩
#   `…/docs(v2)#`,而 `added=1`、`errors=[]`、`partial=[]`、水位照常推进、一行
#   提示都没有(`/path;v=2?…` 和 `/$docs#…` 逐字同样)。
# ②第 6 轮 —— 补完路径字符之后仍然缺 gen-delims 的 `[` `]`,而**这道扫描一直往
#   左跨过路径、authority 乃至 scheme**,所以 authority 里的 IPv6 字面量同样要
#   认:`https://[2001:db8::1]/docs#<别人的文章地址>` 在 `]` 处断掉,留下的尾部
#   只有 `/docs`、再也找不到 `https://`,末态和①逐字相同 —— 库里和导出的 md 里
#   都只剩 `https://[2001:db8::1]/docs#`,`added=1`、`errors=[]`、`partial=[]`、
#   水位照常推进(`https://[2001:db8::1]:8443/docs?…` 同样,它顺带覆盖端口那个
#   `:`;端口本来就认得,断的是方括号)。两条真无头浏览器读回来的 hostname 都是
#   `[2001:db8::1]`、后面那段属于 hash/search,压根不是第二条独立链接。
# **补齐 gen-delims 之后这张表就满了**,不会再有"下一个漏掉的字符" —— 这是取
# 标准全集而不是逐个补样本换来的唯一好处,也是那条契约回归存在的理由。
#
# **加宽也不许加过头**:往这个集合里塞一个**正文里也会出现**的字符(汉字、空白)
# 就会把句读紧贴的真地址一起判成嵌套,而那一侧是**漏认** = 空正文永久固定。
# **已知留着的一道缝:非 ASCII 的路径**(`…/文档#<文章地址>` 那条照旧被摘)。汉字
# 加不进来 —— 它和上面那条放行样本 `参考https://example.org/说明?<文章地址>`
# **完全同形**("往左吃到一个汉字就断"),而那一侧是**漏认**:两头都是永久损坏,
# 不是"哪个对"的问题。线划在 ASCII 上可解释 —— 非 ASCII 不是 URL 的原生形态
# (浏览器要先百分号编码),而编码之后的写法(`/%E6%96%87%E6%A1%A3#…`)由 `%` 和
# 十六进制字符覆盖,本来就判得对。
_URL_RUN = frozenset(
    'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-._~'  # unreserved
    '%'                                                                  # pct-encoded
    "!$&'()*+,;="                                                        # sub-delims
    ':/?#[]@')                                                           # gen-delims
_OUTER_START = re.compile(r'https?://|www\.', re.I)
# 一条 URL 写在推文正文里时,它的尾巴能长到哪儿(查询串、片段、尾斜杠)。下面两条
# 正则都用它,而它们都是拿去 `sub` 掉的 —— 所以这里多认一个字符就是把作者写的字
# 删掉一个,而 `put_items` 的 `DO NOTHING` 让这种删除**永久固定**。
#
# **两道各挡一类,缺一不可**:
# ①**字符类只收 URL 的 ASCII 合法字符**,于是中文(逗号、括号、以及作者正文本身)
#   天然落在外面。**不许写 `\S` 或 `\w`**:`\S` 是"任意非空白",汉字就在里面;
#   而 Python 的 str 模式下 **`\w` 也是 Unicode 的**(`re.match(r'\w+', '中文')`
#   当场命中),所以换成它一样挡不住 —— `_TCO` 原来就是这么漏的。
# ②**结尾必须落在"不像句读"的那一档**(窄集比宽集少了 `.` `,` `;` `:` `!` `?`
#   和闭括号):这些字符在 URL 中间算数,贴在尾巴上的那一个却是作者的标点。
# 另外 `[/?#]` 后面要求至少一个字符(尾斜杠那一支单列),否则
# `Did you read <url>?` 句末那个问号会被当成空查询串吞掉。
#
# 实测这一道挡住的形态(2026-10-09,每一种都是真实推文写法):中文逗号/句号紧贴、
# 中文括号与方括号包住、`?s=20` 与 `#sec3` 之后紧跟中文、英文 `. ` 与 `) ` 收尾。
_URL_TAIL = r'(?:[/?#][A-Za-z0-9_\-=&%.~+/?#:;,!]*[A-Za-z0-9_\-=&%~+/]|/)?'
# 正文里那条指向长文的裸链接(feedgrab 的产物正文就是它)。**两种路径形式都要
# 认**:`/i/article/<article_id>`(t.co 展开出来的那种)和
# `/<handle>/article/<tweet_id>`(X 自己 302 到的**规范形式**,也正是
# `article_page()` 生成的那个地址 —— 见它那条注释)。
#
# 原来只认前一种,而后一种在三条通道上都会出现:**feedgrab** 的产物正文就是展开
# 后的地址(展开成哪一种由上游和 X 说了算,我们看不见也管不着),**浏览器/attach**
# 那边作者写在推文里的可见链接同样可能是它。漏认的后果是 `needs_article` 三条
# 判据一条都不命中(①看不见这个形式,③因为"正文里有字"而不命中,②的卡片信号只在
# 浏览器通道上有、而且某次滚动没渲染出来就没有)—— 于是**那条链接本身被当成正文
# 入库**,而 `put_items` 是 `ON CONFLICT DO NOTHING`,下一轮重抓也更新不了它,
# 那一篇永久只有一个链接(2026-10-09 实测:feedgrab 端到端 `added=1`、
# `errors=[]`、`partial=[]`、水位照常推进,而库里正文就是那条地址、标题回落成
# 「某某 的动态」;浏览器通道没有卡片信号时逐字同样)。
#
# **两个方向的代价差着一个量级**,所以宁可认宽:漏认一种形式 = 空正文永久固定,
# 多认一种 = 最坏一次白跑的询问(答复正好是"它没有长文",照旧入库、不冻水位),
# 口径同 `HINT` 那条注释。**但 handle 的字符类不许放宽**(同 `_STATUS` /
# `_ARTICLE_PATH` 的 `[A-Za-z0-9_]{1,20}`,`/i/` 的 `i` 本来就落在里面):这条
# 正则在 `lead_text` 里是拿去 `sub` 掉的,认宽了会把推文里真实的字删掉。
#
# **「认宽」只对地址的主体成立,尾巴反过来要收窄**(`_URL_TAIL`,原来是 `\S*`)。
# 两个消费方的方向正好相反:判据① 是 `search`,宁可认宽(漏认 = 空正文永久固定);
# `lead_text` 是 `sub`,宁可少删(多删 = 作者的字永久消失)。收窄尾巴恰好只动后者
# —— 地址主体已经足够回答"有没有一条文章地址",尾巴匹配到哪儿对 `search` 的真假
# 一点影响都没有(回归里反过来钉着这一边)。
#
# **起点那一头(`_URL_HOST` + `_nested`)例外:它两个消费方一起收窄,而这不损害
# 判据①。** 被它排掉的串本来就**不是**这条推文自己写的 X 文章地址(主机名是
# `fxtwitter.com`/`notx.com`/`example.org`,或者整条嵌在别人的查询串/片段里),
# 所以真地址的识别一个字都没变窄 —— 收窄的只有"误认"那一半,两个方向同时变好。
# **但那道闸不能是一句"禁掉某几个字符紧贴"**,栽过三次,每一次都是把一条**真**
# 地址挡在正则层面:①不分档时 `新文章...<地址>` 的省略号挡住它;②分档之后
# `读过这篇吗?<地址>` 的句末问号挡住它;③只给 `?` `#` 开上下文判断时
# `全文=<地址>` 的等号挡住它。三种漏认的末态一模一样:判据① 一条都不命中、空正文
# 永久固定 —— 那就不再是"只收窄误认"了。所以①那一档的起点在正则里**一个字符都不
