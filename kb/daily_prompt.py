# -*- coding: utf-8 -*-
"""日报的提示词:出稿结构,以及「出稿长度不许随素材条数线性增长」那一条。

**和取材分开两个文件**:取材回答"这一份带走哪些条目"(名额、账本、窗口),这里
回答"这一批条目写成多长的一篇"。两件事的上限各有各的理由 —— `daily.MAX_ITEMS`
的上界是模型吃得下多少素材,`_LATE_CAP` 的上界是 `llm.chat` 的 `max_tokens`
出得了多长的稿 —— 混在一处的后果是调前者时顺手把后者撑爆。
"""
from __future__ import annotations

PROMPT = """你是这个知识库主人的情报助理。下面是 {range_label} 这段时间里**发布**的 {n} 条内容\
(来自公众号、社交观点、RSS 订阅和视频摘要)。请写一份日报。

输出要求:
- 全中文,直接输出 markdown 正文,不要代码围栏,不要重复标题行。
- 每条结论后面用编号标注出处,如 [3][7];编号就是下面列表的序号。
- 只依据下面给出的材料写,不要编造事实、数字、评价;材料没说的不要推断。
- 不要逐条复述所有内容,该合并的合并,该舍弃的舍弃。

结构严格如下:

## 今日要点

3~6 条真正值得知道的事。每条一个列表项:**一句话点明事件**,再用一两句说清\
"是什么、为什么值得注意"。教程、旧闻盘点、招聘、纯营销不算要点。

## 工具与项目

这段时间出现的、可以拿来用的开源项目或产品。每条一行:名字 — 一句话说明它解决什么问题。\
最多 20 行,同一个东西被好几篇提到就合成一行。\
没有就写"这段时间没有值得单独拿出来的新工具"。

## 观点与讨论

社交观点和评论里值得留意的看法,1~4 条。没有就写一行"没有明显的讨论热点"。

## 一句话速览

其余内容各一行,一行不超过 30 字。最多 12 行,超出的不写。
{late_section}
材料:
{items}
"""

# 补录那一节最多占多少行。**出稿长度不许随素材条数线性增长** —— `llm.chat` 的
# `max_tokens` 是 8192,而"每条一行"在补录超过约 150 条时会让出稿从素材清单中间
# 直接断掉,**而这一批条目照样全部被盖章**(盖章认的是"进过这一份的输入",不是
# "正文里提到了"),于是一份坏产物配一批写死的章、重跑也选不回来。
# 一次为了排干 305 条补录,得手改提示词才跑得出来 —— 那个改动不该只活在手上。
_LATE_CAP = 30


def late_section(n: int) -> str:
    """补录那一节的指令,**随条数退化**:少的时候一条一行,多了就归并。

    退化的是"出稿怎么写",不是"带走多少条" —— 名额仍然由 `LATE_ITEMS` 定,
    这里只保证那些条目落进一段长度有上限的正文里。
    """
    if n <= _LATE_CAP:
        return """
## 补录

材料里标了「补录」的,是发布时间更早、这一轮才抓进来的内容。每条一行,\
写清它是什么、发布于什么时候。上面四节不要提它们。
"""
    return f"""
## 补录

材料里标了「补录」的,是发布时间更早、这一轮才抓进来的内容,这一批共 {n} 条。\
**按来源和主题归并着写,最多 {_LATE_CAP} 行**:每行一类,点出这一类里值得看的那几条\
(带上它们是什么、发布于什么时候),其余的在该行末尾用"另有 N 条"收掉。\
一条一行会超出出稿长度、把清单从中间截断,所以不要逐条罗列。上面四节不要提它们。
"""
