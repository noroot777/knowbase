# -*- coding: utf-8 -*-
"""日报那一页的 markdown:素材清单怎么写出来、怎么读回来。

从 `kb.daily` 里拆出来**只因为行数**(那边到了 700 行上限)。这边只认字符串,
不碰库、不碰 vault:一半是写那一页时的转义(`md_dest` / `md_text` / `md_title`),
另一半是启用账本时从一份已有日报里把「它实际带走了哪些素材」读回来
(`carried_keys`)。**两半必须待在一起** —— 读回来那一侧比的就是写出去的那串
字符(`doc_key` 拿 `md_dest` 归一),分到两个文件里就是等着各漂各的。

`kb.daily` 把这几个名字按原来的私有名绑回自己的模块全局(`daily.md_dest` 这类
既有写法照旧有效),调用点一个字都没改。
"""

from __future__ import annotations

import re

# 素材清单里「标题」和「来源·账号」之间的分隔符。拼装(`_page`)和读回来
# (`carried_keys`)共用这一份 —— 迁移盖章靠它把标题从那一行里切出来。
REF_SEP = ' — '


def md_dest(url: str) -> str:
    r"""markdown 链接的目标一律用尖括号包起来。

    库里的 url 实测有带圆括号的(`…-(clean).pdf`、`S2589-0042(26)00811-4`),
    裸写进 `](…)` 里会在第一个 `)` 处提前收尾,链接当场断掉、后半截漏成正文。
    尖括号里唯一不能裸出现的是 `<` `>` 本身,转义掉。

    `|` 也得编码:GFM 是**先按行拆单元格再解析 inline** 的,尖括号拦不住它 ——
    一条目标带 `|` 的链接写进表格,那一格从 `|` 处当场裂成两格,右边的内容被挤
    出表外(2026-09-30 第 4 轮审查实测)。`%7C` 和 `\|` 渲染出来的 href 逐字
    相同,编码那种在非 markdown 场景下也对。
    """
    return ('<' + ' '.join(str(url or '').split())
            .replace('<', '%3C').replace('>', '%3E').replace('|', '%7C') + '>')


def md_text(text: str) -> str:
    """链接文字里的方括号一律转义。

    库里十来篇标题带着 `[视频]`、`[四川话、粤语等]` 这种写法,平衡的还好,
    落单一个就能把素材清单那条链接从中间截断 —— 后半截标题漏成正文、url
    露在外面。
    """
    return (str(text or '').replace('\\', '\\\\')
            .replace('[', '\\[').replace(']', '\\]'))


def md_title(text: str) -> str:
    """链接标题里的 `|` 要转义 —— 库里 215 篇文章标题带着它(`AI Weekly 016 | 开源
    项目与科技进展` 那种)。GFM 先拆单元格再解析 inline,标题里一个裸 `|` 就把那
    一格从中间劈开:出处那格变成半截标题,右边「已可用」被挤出表外、页面上再也
    看不见(2026-09-30 第 4 轮审查实测)。`\\|` 在表格内外渲染结果一致。"""
    return (' '.join(str(text or '').split())
            .replace('\\', '\\\\').replace('"', '\\"').replace('|', '\\|'))


# 「素材清单」那一节(`_page` 写的):每一份日报自己记着它到底带走了哪些条目。
# 迁移盖章只认这一份证据,所以下面这几个和 `_page` 里拼 `refs` 那几行是一对 ——
# 分隔符共用 `REF_SEP` 一份,改那边的格式要跟着改这边。认不出来的行当成"这一条
# 没有证据",不盖章(方向按元规则:多报一遍,不写死)。
_MATERIAL_HEAD = '## 素材清单'
_MATERIAL_ROW = re.compile(r'^\s*(\d+)\.\s+(.+)$')
# 链接那一支要同时顶住几种真实写法,各踩过一次:①最老那几份日报的链接目标是
# **裸** `(url)` —— `md_dest` 是后来才加的(实测生产库 2026-09-30 那一份整份
# 如此),只认尖括号就读不出它的归属;②**账号名里带圆括号**(`歸藏(guizang.ai)`)
# —— 所以不能贪婪吃到最后一个 `)`,`.+?` 配上「右括号后面紧跟分隔符或行尾」这个
# 锚点才落在 url 自己那一个上;③**url 自己带圆括号**(那正是 `md_dest` 存在的
# 理由)—— 非贪婪会在它那里先试一次、锚点不成立再往后退;④**匹配到分隔符就收工,
# 不要求吃到字符串末尾** —— 清单末尾那句引用块会跟着并进最后一条里来;⑤**方括号
# 转没转义要按连续反斜杠的奇偶数**(`(?<!\\)(?:\\\\)*`),光问「紧挨着的那一个
# 是不是反斜杠」会把 `md_text` 写出来的**成对**反斜杠误当成转义 —— 标题末尾是
# `C:\models\` 的那条链接因此整条读不出来,归属跟着丢掉。
_MATERIAL_LINK = re.compile(
    r'^\[[\s\S]*?(?<!\\)(?:\\\\)*\]\((.+?)\)(?:' + REF_SEP + r'|$)', re.M)
# 「— 来源·账号」那半截:一条素材的收尾。**光看有没有 `REF_SEP` 不够** —— 大V观点
# 那一档的"标题"是推文正文,里面自带一个 ` — ` 是很平常的事,而真正的收尾后面一定
# 紧跟着 `来源·账号`(`_page` 拼的就是这个)。
_ENTRY_TAIL = re.compile(REF_SEP + r'[^\n\u00b7]*\u00b7')


def doc_key(url, title) -> str:
    """一条素材在日报「素材清单」里的身份。盖章和读清单两侧共用这一份口径。

    有 url 就按 url、没有的按标题(清单里那一行也正是这么分的两支)。url 一律
    过一遍 `md_dest` 归一(包尖括号、把 `<>|` 编码掉、空白压掉),它幂等,所以
    裸写法和尖括号写法、库里的原值和文件里那串字符会落到同一个键上 —— 两侧各
    归一各的,匹配率是 0。标题同理压掉空白:推文标题里带换行,清单里也原样带着。
    """
    return (md_dest(url) if str(url or '').strip()
            else '题:' + ' '.join(str(title or '').split()))


def _closed(text: str) -> bool:
    """这一条素材读完了吗 —— 决定下一行的编号开头算不算**新**的一条。

    光看「这一行是不是 `N. ` 开头」不够:大V观点那一档的"标题"是推文正文,里面
    常常自带有序列表(「1. 先阅读说明」「2. 再运行示例」),那几行会被当成独立素材
    拆出去,真正那条的链接跟着被劈成两半、读不到 url —— 于是窗口里已经报道过的
    观点次日又被取材一遍,而发布时间早于链起点的那些干脆被记成 `#seed`、重新生成
    时一条都选不回来(真实页面复现)。

    **两种结束写法都算数,不许按「是不是 `[` 开头」二选一** —— 没有 url 的那一支
    标题是**裸**写进去的(`_page` 对它一个字符都不转义),所以一条「[视频] …」开头
    的补录看起来和链接那一支的开头一模一样。要求它等一个永远不会出现的 `](…)`,
    下一条就被并进来,两条的归属一起丢掉、双双记成 `#seed`,**重新生成那一天时
    一条都选不回来**(真实页面复现)。

    **反过来,「有 `REF_SEP` 就算读完」又太松**:推文正文里带一个 ` — ` 很平常,
    那一条会在半截处被切开。所以第二支认的是**整个收尾结构**(`_ENTRY_TAIL`:
    分隔符后面紧跟 `来源·账号`),而且**只在最后一行上问** —— `_page` 把收尾拼在
    一条的末尾,跨行标题中间那些行不该作数。
    """
    return (_MATERIAL_LINK.match(text) is not None
            or _ENTRY_TAIL.search(text.rsplit('\n', 1)[-1]) is not None)


def _ref_key(text: str) -> str:
    """素材清单里一条(可能跨行)的身份。"""
    link = _MATERIAL_LINK.match(text)
    if not link:
        # 没有链接的那一支:尾巴上的「— 来源·账号」摘掉,剩下的是原样写进去的标题
        return doc_key('', text.rsplit(REF_SEP, 1)[0])
    dest = link.group(1).strip()
    # 括号里那一截交给 `doc_key` 归一,这里只剥掉尖括号那层壳
    return doc_key(dest[1:-1] if dest[:1] == '<' and dest[-1:] == '>' else dest, '')


def flat(text) -> str:
    """归一成"能和清单原文逐字比"的样子:反斜杠是转义留下的痕迹,空白一律压平。

    同一个标题在清单里有两种写法 —— 链接那一支过了 `md_text`(方括号被转义成
    `\\[`),没有 url 的那一支是**裸**写的;而推文标题自带换行,库里那份和文件里
    那份的空白也对不上。两边各过一遍这个函数,写法差异就不参与判断了。
    """
    return ' '.join(str(text or '').replace('\\', '').split())


def material_rows(body: str) -> tuple[str, ...]:
    """这一份日报的素材清单,一条一条(归一过),用来回答"这一篇露过面吗"。

    读不出身份的那一条交不出归属,按"不盖章"办 —— 可那只是不盖**归属**,它随后
    还要落到"发布早于链起点 ⇒ 历史存量 `#seed`"那一档上,而 `#seed` 对任何一天的
    重新生成都满足排除条件,**永久写死**。于是"解析漏了一种写法"的后果从"多报
    一遍"升级成"那条内容再也回不来":连着三轮审查各找出一种新写法(跨行标题、
    标题自带有序列表、裸方括号开头、成对反斜杠),**这份清单不会收敛**。

    所以给结论本身加一道:凡是在清单原文里露过面的内容,这一次就别下"它是链条
    之前的历史存量"这个结论 —— 它明明被某一份日报写出去过。代价是多报一遍,而
    那正是元规则要的那一边。能正常读出身份的那些早在上一档就盖完了,走到这里的
    恰恰是解析没跟上的那几条。

    **这不是"给标题加兜底匹配"**(那条禁止的是拿标题去**盖归属** —— 同稿副本会让
    另一篇同名文章被当成报过了,方向是不可恢复的那一边)。这里只用来**否决**一个
    终态,同名撞上的后果仍然是多报一遍。
    """
    return tuple(flat(t) for t in _rows(body))


def carried_keys(body: str) -> set[str]:
    """一份已有日报**实际带走了**哪些素材 —— 从它自己的素材清单里读回来。

    为什么非得读清单、不能按发布时间推断,见 `daily_carry.ensure_ledger`:推断在
    两头各错一次(补录被当成链条之前的存量、名额装不下的被记成报过了),两处都
    不可恢复。读不出来的那一份交空集合,它提供不了任何归属证据。

    **一条素材不一定只占一行,而且断不开**:大V观点那一档的"标题"是推文正文的前
    500 字符,里面既有换行**也有空行**(实测生产库一份日报里 31 条都是这个形态)。
    按行各认各的会把它们全判成认不出来 —— 它们明明在库里、发布时间也在链条覆盖
    的那段里,于是被当成"没报过"重新倒灌进下一份日报。所以除了编号开头的那种行,
    其余一律并回上一条,**不拿空行当分界**;末尾那句引用块也会并进最后一条,由
    `_MATERIAL_LINK` 那条"匹配到分隔符就收工"消化掉。

    **编号开头的行也不一定就是新的一条**(推文正文里自带有序列表),所以那一支还
    要过两道:①**编号得接得上** —— 清单是 `enumerate(shown, 1)` 写出来的,所以
    第一条必然是 `1.`、后面每条都恰好比上一条大一,而推文正文里那截列表多半从 1
    重新数起、接不上;②上一条读完没有(判据见 `_closed`)。**两道缺一不可**:
    编号那道挡不住「推文里的 2. 正好接在真实的第 1 条后面」,`_closed` 挡不住
    「标题自带分隔符」,各自都有自己漏的那一种。
    """
    return {_ref_key(t) for t in _rows(body)}


def _rows(body: str) -> list[str]:
    """把素材清单切成一条一条,每条给它的原文(可能跨好几行)。"""
    head = body.rfind(_MATERIAL_HEAD)      # 取最后一处:正文里要是也写了这四个字
    if head < 0:                           # (模型偶尔会),清单永远在它后面
        return []
    rows: list[list[str]] = []
    for line in body[head:].splitlines()[1:]:
        m = _MATERIAL_ROW.match(line)
        if (m and int(m.group(1)) == len(rows) + 1
                and (not rows or _closed('\n'.join(rows[-1])))):
            rows.append([m.group(2)])
        elif rows:
            rows[-1].append(line)
    return ['\n'.join(r) for r in rows]
