// 生成按钮那一行:按钮自己的名字、它前面那句「有 N 条新内容」,以及挂在两者身上
// 的那段 tooltip(今天第 N 次抓取、抓了多少、那个数由什么构成、队列里还积着多少)。
//
// 单独一个文件是因为这一处的说法最多:一句可见文案背后有三档事实,tooltip 里还有
// 六种抓取事实各一句、三档归属各一句分解,而 daily.js 已经扛着定时设置、历史日报、
// 阅读区三摊事。改这里不影响那三摊。
//
// 读的是 daily.js 的 `dailyWindow` / `dailyReports` / `dailyWindowDirty`
// (同一个全局作用域,index.html 里按序加载)。

function dailyTargetDate() {
  // 这一次会写到哪一天那份日报上。**只有这一份口径**:按钮叫"生成"还是"重新
  // 生成"、要不要先弹覆盖确认,问的是同一件事,两处各判一遍必然各漂各的。
  // 自定义区间落在截止时刻那天,默认区间落在今天(生成时刻)。
  return dailyWindowDirty && $('daily-until').value
    ? $('daily-until').value.slice(0, 10)
    : new Date().toLocaleDateString('sv');
}

function dailyTargetReport() {
  // 「这一次会写到的那一天,有没有一份日报」—— **只有这一份口径**,三个消费者:
  // 按钮叫什么名字、点下去要不要先弹覆盖确认(`runDaily`)、以及没有新内容时
  // 能不能把按钮**藏掉**。三档:
  //   true  = 核实过:**此刻磁盘上**就有(window 那一趟带回来的 `has_report`,
  //           和 `gain` 同一次读、同一个回包);
  //   false = 核实过:没有;
  //   null  = **没核实过**,只是手里那份列表缓存这么说。
  //
  // 为什么要分出 null:列表缓存只在列表重读时才更新,而空闲轮询只刷新 window。
  // 在 Obsidian 里把今天那份移走(没走界面那条删除)之后,缓存会一直说"还在"、
  // `gain` 照样是 0,于是"重建今天那一份"的唯一入口被一直藏着,只有整页刷新才
  // 回来(审查实测)。名字和确认框照缓存说没关系(说错顶多多问一句),
  // **藏按钮不认猜**。
  //
  // **反过来,这份回包里的"没有"一旦过期就不许再用。** 生成、删除、以及最新一趟
  // 读失败之后它就不是"此刻"了 —— 前两条各自会把列表和这份回包一起重读,第三条由
  // `fetchDailyWindow` 的 catch 把 `has_report` 一并抹成 null(一句过期的"今天没有
  // 日报"会让再点一次生成**不弹覆盖确认**,静悄悄盖掉刚出的那一份,审查实测)。
  // 抹掉之后这件事退回列表那份:它含着今天 ⇒ null(不知道)⇒ 照旧问一声。
  // 两趟 window 之间的先后由 `dailyWindowSeq` 管,迟到的那趟整趟作废,所以**读成功
  // 的那一份一定比列表新**(生成/删除都是两样一起重读)。
  //
  // 自定义区间要写的是另一天,后端答的不是它 —— 那时整段事实都退回缓存,而
  // `gain` 本来就不参与(见下),按钮照显示。
  const day = dailyTargetDate();
  if (dailyWindow && dailyWindow.day === day
      && typeof dailyWindow.has_report === 'boolean') return dailyWindow.has_report;
  return dailyReports.some(r => r.date === day) ? null : false;
}

function renderDailyGenButton() {
  // 这颗按钮的名字跟着"那一天有没有日报"走:已经有就是**重新生成**(点下去会
  // 覆盖它,所以还会弹一次确认),没有就是头一份。写死成"重新生成"的话,第一次
  // 用的人会以为自己漏掉了一步。**不知道的时候按"有"说** —— 名字说错只是难看,
  // 而把"可能会覆盖"说成"头一份"会让人在没有确认框的情况下盖掉一份日报。
  const exists = dailyTargetReport();
  // 勾了「先同步一轮」就把它写进按钮名字里。**名字必须跟着那个勾走** —— 页头只剩
  // 一颗按钮,点下去到底会不会先同步,只能从它自己身上看出来(原来那是两颗按钮的
  // 区别,而那个区别哪儿都没写,正是用户说「乱」的地方)。
  const presync = !!$('daily-presync')?.checked;
  const base = exists === false ? '生成日报' : '重新生成日报';
  $('daily-gen-label').textContent = presync ? '同步后' + base : base;

  // 按钮前面那句话报的是 `gain`:**再生成一次会多带进来几条没进过日报的内容**
  // (后端口径在 `daily.pending`:和真取材共用一个 `_select`,同样先截名额再数)。
  //
  // **它同时决定这颗按钮还要不要显示。** `gain=0` 意味着重新生成会原样挑回今天
  // 那一份已经带走的那批,内容一个字都不会多 —— 留着一颗点下去只会花一次模型钱、
  // 拿回同一份日报的按钮,就是在请人做一件没有后果的事。此时只留一句灰字说明它
  // 为什么不在(整段都不画的话,按钮会毫无交代地消失)。
  //
  // **不许拿别的数冒充它**,三个数答的是三个问题:抓回来 860 篇(`fetch.added`,
  // 抓取自己的事实)、队列里一共还积着 1097 条(`pending.total`)、而这一次生成
  // 只多带得进 11 条。生产库实测的正是后两个数,把队列总长写在这里,用户会照着
  // 它花一次模型钱、拿回多出 11 条的日报。那两个数整条进 tooltip。
  //
  // 三档事实三句话:
  // ① 知道且 >0 → 「有 N 条新内容」(品牌深绿),按钮显示;
  // ② 知道且 =0 **而且核实过那一天的日报此刻就在** → 「没有新内容」(灰),
  //    按钮**整颗藏掉**。两个条件缺一不可,而且都得是**核实过**的:账本盖的章和
  //    vault 里那个文件是两头东西,文件被移走时章还在、`gain` 照样是 0,这时藏掉
  //    按钮等于把"重建今天那一份"的唯一入口也一起藏了(判据在 `dailyTargetReport`);
  // ③ **不知道** → 说「新内容读不出来」、**照常显示按钮**。两档都算不知道:
  //    后端答 `pending: null`(整份算不出来),以及 `pending.gain: null`
  //    (两个数算出来了,只有"会不会多带进内容"这一问答不上来 —— 今天那份里有
  //    一条账本没记下当时那一版)。**旧后端压根没给 `gain` 这个字段**时整段不说、
  //    按钮照显示(按形状判,不猜后端是哪一版;`kb/static/` 免重启而 server.py
  //    要重启,这一刻天天走到)。把"不知道"当成"没有"的后果是一次读取故障就把
  //    出报这条路堵死,而页面上一个字都不说。
  //
  // **改过覆盖区间时整段藏掉、按钮照显示**:后端算的是默认区间那一段,拿它去
  // 回答"我填的这一段里有多少新内容"是另一个问题的答案。这也是 `gain=0` 时把
  // 按钮找回来的那条路(另一条是删掉今天那份日报)。
  const line = $('daily-new-count');
  const p = dailyWindowDirty ? undefined : dailyWindow?.pending;
  const gain = typeof p?.gain === 'number' ? p.gain : null;
  const unreadable = !dailyWindowDirty && !!dailyWindow
    && (dailyWindow.pending === null || (!!p && p.gain === null));
  line.hidden = gain === null && !unreadable;
  line.textContent = unreadable ? '新内容读不出来'
    : gain > 0 ? `有 ${gain} 条新内容` : '没有新内容';
  line.classList.toggle('is-none', !gain);

  // **「这一次生成一个字都不会多」时置灰,不是藏掉。** 藏掉是两颗按钮时代的做法
  // (那时「同步全部并生成」还在,出路没断);页头并成一颗之后,藏掉会把「先同步
  // 一轮」这条路一起藏了 —— 而没有新内容时,先同步正是该做的那件事。更要紧的是
  // 藏掉让人**发现不了**那条出路:按钮不在,旁边那个勾就成了一个没有去处的勾。
  // 置灰 + 把出路写在它上面,既没请人做一件没有后果的事,也没把入口堵死。
  //
  // **勾了「先同步」就恢复可点**:同步会带进新内容,「这一次不会多带」那个判据
  // (后端按**现有库存**算的 `gain`)对它压根不成立。
  const noGain = gain === 0 && exists === true;
  // 这颗按钮点不点得了,只在这一处算 —— `renderDailyButtons` 不再另算一遍,
  // 两处算迟早在某一档上岔开。`dailyBusy` / `dailyState` 是 daily.js 的全局
  // (这个函数本来就在读 `dailyWindow` / `dailyWindowDirty`,同一套)。
  $('daily-gen').disabled = !!window.dailyBusy || !!dailyState?.running
                            || (noGain && !presync);

  // tooltip 带着**抓取自己的事实**:今天第 N 次抓取往库里新加了多少篇。一天内
  // 同步第二次之后,得有个地方让人看出这次抓回来多少 —— 它和上面那个数必然不等
  // (名额、补录回溯范围、软广与衍生树都在中间),所以各待各的位置。同理,生成
  // 完日报这个数**不该归零**:抓取事实没有因为出了一份日报而改变。
  //
  // 自定义区间时照样说 —— 抓取事实和区间选哪一段无关(队列那句跟着藏掉,后端
  // 算的是默认区间那一段)。
  //
  // 五种说法对五种事实,**不许合并**:没问过后端(undefined)只留空;后端答
  // 「不可确认」(null:账本整份读不出来,或者有行没落下去)说「读不出来」;
  // `n=0` 才是「今天还没有抓取」。把 null 也说成「还没有抓取」是在把"不知道"说成
  // "没有",而一次写失败之后它会一直这么笃定地说下去。
  //
  // 剩下两种是**这一轮的条数全不全**(`partial`):勾了三个来源而第三个炸在半路、
  // 采集器给不出清单时,已知的那几条只是**下界** —— 那就说「至少 N 篇」,一条
  // 都说不出来时说「条数读不出来」。把下界写成确定值的后果是用户照着一个偏小的
  // 数决定不重新生成日报,而真落进库的比它多(口径见 `kb/fetch_rounds.py`)。
  //
  // 两处都挂同一段话:`gain=0` 时按钮不在了,这些事实得还有地方能看。
  // 置灰的原因和出路要写在按钮上 —— 一颗点不动、又不说为什么的按钮,和坏了
  // 长得一模一样。抓取事实那段照旧两处都挂(口径没动)。
  $('daily-new-count').title = dailyCatchTip();
  $('daily-gen').title = (noGain && !presync
    ? '这一次生成不会多带进任何内容；勾上「先同步一轮」可以先取一遍新内容。\n' : '')
    + dailyCatchTip();
}

function dailyCatchTip() {
  const f = dailyWindow?.fetch;
  if (f === undefined) return '';
  const p = dailyWindowDirty ? null : dailyWindow?.pending;
  // 「后面几天会陆续带走」是句许不出来的承诺:补录每天有名额,而排到超过
  // BACKLOG_DAYS 的会直接退出候选,不是一定进得了日报。
  const queued = p?.total
    ? `队列里有 ${p.total} 条还没进过任何日报，留待后续日报择取（超出回溯范围的不再纳入）。`
    : '';
  return (f === null
    ? '当日抓取账本读不出来，今天抓了几次暂时不可确认（不是「没抓到」）。'
    : f.n
      ? (f.partial
        ? `今天第 ${f.n} 次抓取${f.at ? `（${f.at}）` : ''}有一段成果没能确认，`
          + `已知新加了 ${f.added} 篇，实际可能更多。` + dailyCatchSplit(f)
        : `今天第 ${f.n} 次抓取${f.at ? `（${f.at}）` : ''}往库里新加了 ${f.added} 篇。`
          + dailyCatchSplit(f))
      : '今天还没有同步过，库里的内容和上一次一样。') + queued;
}

function dailyCatchSplit(f) {
  // 抓回来那些由什么构成。**只在有补导或说不清的时候才说** —— 全是这一次新
  // 抓到的(正常情形)时候,再补一句「其中 3 篇是这一次新抓到的」只是把同一个数
  // 说两遍。反过来,`fresh=0 / carried=3` 恰恰是最该说的那一档,所以判据是
  // 「有没有不是本次抓到的」,不是「拆得出几档」。
  //
  // 为什么要有这句:那个数报的是「这次同步之后日报能多拿到多少」(仓库主人定的
  // 口径),而它和「远端这次新发现多少」在补导场景下必然不等 —— 正文抓取当天失败、
  // 隔两天补上才导出,那几篇是前几天抓到的。远端今天一条新内容都没发而按钮写
  // 「+3 条」时,用户得能看出这 3 条值不值一次模型钱。
  //
  // 三档各有自己的话,**不许把「说不清」并进「补导」**:抓取身份是空串时我们只
  // 知道「没记过」(存量内容、手工导入的链接),不知道「不是这一次」。并进去就是
  // 把"不知道"说成"确定不是"。口径在 `kb/fetch_rounds.py` 的 `today`。
  //
  // **三个字段要齐,差一个就整句不说。** 这不是防御性冗余:kb-web 的
  // `kb/static/` 每次请求从磁盘读、而 server.py 要重启才生效,所以「新前端 +
  // 旧后端」是这个项目里天天走到的那一刻(见 CLAUDE.md「服务与运行时」)。
  // 三个全缺时下面那道闸恰好也会挡住(`!undefined` 为真),**真正只有这一道
  // 挡得住的是半份答案** —— 答了 `carried` 没答 `fresh` 时,写出去的会是
  // 「新加了 4 篇。其中 3 篇是之前抓到的」,一个加不起来的分解,而那第 4 篇
  // 到底怎么来的页面上一个字都没有。按**形状**判,不去猜后端是哪一版。
  if (!f || [f.fresh, f.carried, f.unsure].some(n => typeof n !== 'number')) return '';
  if (!f.carried && !f.unsure) return '';
  const parts = [];
  if (f.fresh) parts.push(`${f.fresh} 篇是这一次新抓到的`);
  if (f.carried) parts.push(`${f.carried} 篇是之前抓到、这一次才补导进来的`);
  if (f.unsure) parts.push(`${f.unsure} 篇说不清是哪一次抓到的`);
  return parts.length ? `其中 ${parts.join('，')}。` : '';
}
